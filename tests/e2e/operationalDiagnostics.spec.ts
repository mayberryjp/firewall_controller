  await expect(row.locator("td")).toHaveCount(6);
  await expect(dns.getByRole("columnheader", { name: "Result", exact: true })).toBeVisible();
  await expect(row.getByRole("cell", { name: "192.0.2.53", exact: true })).toHaveCSS("white-space", "nowrap");
  await expect(dns.getByRole("combobox")).toHaveCount(0);
  await expect(dns.getByRole("spinbutton")).toHaveCount(0);
  await row.getByRole("textbox", { name: "Domain for 192.0.2.53", exact: true }).fill("Example.TEST.");
