import { expect, test } from "@playwright/test";
import { mockBackend } from "./mockBackend";
import { dnsResponse, linkDiagnostics } from "../diagnosticsFixtures";
import { config, processHealthSnapshot } from "../fixtures";
import { encodeJson } from "../../src/services/json";
import { dnsLookupRequestSchema } from "../../src/services/operations";

test("DNS lookup, focused diagnostic tables and icon-only confirmed restart", async ({ page }, testInfo) => {
  const initialConfig = config();
  initialConfig.dns = { lab0: { servers: ["192.0.2.53"], domains: [] } };
  initialConfig.interfaces.push({ ...initialConfig.interfaces[0]!, name: "wan0", role: "wan", addresses: ["203.0.113.1/24"] });
  initialConfig.routes.push({ enabled: true, destination: "192.0.2.53/32", interface: "wan0", table: 254, metric: 1 });
  const backend = await mockBackend(page, { initialConfig });
  const restarts: unknown[] = [], lookups: unknown[] = [];
  await page.route("**/proxy/platform/status", route => route.fulfill({ contentType: "application/json", body: encodeJson(processHealthSnapshot()) }));
  await page.route("**/proxy/statistics/link-diagnostics", route => route.fulfill({ contentType: "application/json", body: encodeJson(linkDiagnostics()) }));
  await page.route("**/proxy/diagnostics/dns-lookup", route => {
    const request = dnsLookupRequestSchema.parse(route.request().postDataJSON());
    lookups.push(request);
    const server = request.server;
    if (!server) return route.fulfill({ status: 400, contentType: "application/json", body: encodeJson({ error: "Explicit server required by this fixture" }) });
    const response = dnsResponse();
    return route.fulfill({ contentType: "application/json", body: encodeJson({
      ...response, server, hostname: request.hostname, attempts: response.attempts.map(attempt => ({ ...attempt, server })),
    }) });
  });
  await page.route("**/proxy/processes/restart", route => {
    restarts.push(route.request().postDataJSON());
    return route.fulfill({ contentType: "application/json", body: encodeJson({ target: "ntp", status: "restarted", worker: { name: "ntp", state: "running" } }) });
  });
  await page.goto("/connect");
  await page.getByLabel("Registry admin password").fill("registry-test-password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("button", { name: "Connect", exact: true }).click();
  await expect(page.getByRole("region", { name: "Overview", exact: true })).toBeVisible();
  await page.goto("/services/remote-dns");
  const dns = page.getByRole("region", { name: "Remote DNS", exact: true });
  const row = dns.locator("tbody tr").filter({ has: page.getByRole("cell", { name: "192.0.2.53", exact: true }) });
  await expect(row.locator("td")).toHaveCount(6);
  await expect(dns.getByRole("columnheader", { name: "Result", exact: true })).toBeVisible();
  await expect(row.getByRole("cell", { name: "192.0.2.53", exact: true })).toHaveCSS("white-space", "nowrap");
  await expect(dns.getByRole("combobox")).toHaveCount(0);
  await expect(dns.getByRole("spinbutton")).toHaveCount(0);
  await row.getByRole("textbox", { name: "Domain for 192.0.2.53", exact: true }).fill("Example.TEST.");
  await row.getByRole("button", { name: "Test DNS 192.0.2.53", exact: true }).click();
  await expect(row.getByRole("cell", { name: "RTT for 192.0.2.53" })).toHaveText("13 ms");
  await expect(row.getByRole("cell", { name: "Result for 192.0.2.53" })).toContainText("192.0.2.7");
  expect(lookups).toEqual([{ server: "192.0.2.53", hostname: "example.test", record_type: "A", timeout_ms: 2000 }]);
  await dns.getByRole("button", { name: "Add DNS server", exact: true }).click();
  await dns.getByRole("textbox", { name: "DNS server", exact: true }).fill("1.1.1.1");
  await dns.getByRole("button", { name: "Save", exact: true }).click();
  const draftRow = dns.locator("tbody tr").filter({ has: page.getByRole("cell", { name: "1.1.1.1", exact: true }) });
  await draftRow.getByRole("textbox", { name: "Domain for 1.1.1.1", exact: true }).fill("Draft.TEST.");
  await draftRow.getByRole("button", { name: "Test DNS 1.1.1.1", exact: true }).click();
  await expect(draftRow.getByRole("cell", { name: "RTT for 1.1.1.1" })).toHaveText("13 ms");
  await expect(draftRow.getByRole("cell", { name: "Result for 1.1.1.1" })).toContainText("192.0.2.7");
  expect(lookups[1]).toEqual({ server: "1.1.1.1", hostname: "draft.test", record_type: "A", timeout_ms: 2000 });
  expect(backend.writes).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("remote-dns.png"), fullPage: true, animations: "disabled" });
  await page.goto("/diagnostics/link-diagnostics");
  await expect(page).toHaveURL(/\/diagnostics\/interface-drops$/);
  const drops = page.getByRole("region", { name: "Interface drops", exact: true });
  await expect(drops).toContainText("Current");
  await expect(drops).toContainText("18446744073709551615");
  await expect(drops.getByRole("columnheader", { name: "Drops delta", exact: true })).toBeVisible();
  await expect(drops.locator(".v-chip").filter({ hasText: /^1$/ })).toHaveClass(/text-warning/);
  await expect(drops.locator(".v-chip").filter({ hasText: /^18446744073709551615\s*\+1$/ })).toHaveClass(/text-warning/);
  await expect(drops).not.toContainText("Queue (packets)");
  await page.screenshot({ path: testInfo.outputPath("interface-drops.png"), fullPage: true, animations: "disabled" });
  await page.getByRole("tab", { name: "QDISCS", exact: true }).click();
  const queues = page.getByRole("region", { name: "QDISCS", exact: true });
  await expect(queues).toContainText("fq_codel");
  await expect(queues).toContainText("-256");
  await expect(queues.locator("tbody tr").first().locator("td").nth(10).locator(".v-chip")).toHaveClass(/text-warning/);
  await expect(queues).not.toContainText("Zero-window observations");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("qdiscs.png"), fullPage: true, animations: "disabled" });
  await page.getByRole("tab", { name: "TCP WINDOWING", exact: true }).click();
  const windows = page.getByRole("region", { name: "TCP WINDOWING", exact: true });
  await expect(windows).toContainText("Capture incomplete");
  await expect(windows).not.toContainText("Router-local TCP");
  await expect(windows).not.toContainText("future_evidence_code");
  await expect(windows.getByRole("columnheader", { name: "Zero-window observations", exact: true })).toBeVisible();
  await expect(windows.locator("tbody tr").first().locator("td").nth(4).locator(".v-chip")).toHaveClass(/text-warning/);
  await expect(windows.getByText("Kernel drops", { exact: true })).not.toBeVisible();
  await expect(windows.locator("table")).toHaveCount(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("tcp-windowing.png"), fullPage: true, animations: "disabled" });
  await expect(windows.getByRole("link", { name: "Capture details", exact: true })).toHaveCount(0);
  await page.getByRole("tab", { name: "Capture details", exact: true }).click();
  await expect(page).toHaveURL(/\/diagnostics\/capture-details$/);
  const capture = page.getByRole("region", { name: "Capture details", exact: true });
  await expect(capture).toContainText("Capture incomplete");
  await expect(capture.getByRole("columnheader", { name: "Kernel drops", exact: true })).toBeVisible();
  await expect(capture).toContainText("18446744073709551615");
  await expect(capture).toContainText("help distinguish real network problems from missing or truncated capture data");
  await expect(capture.locator(".v-chip").filter({ hasText: /^18446744073709551615$/ })).toHaveClass(/text-warning/);
  await expect(capture).not.toContainText("Zero-window observations");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("capture-details.png"), fullPage: true, animations: "disabled" });
  await page.goto("/diagnostics/process-health");
  const restart = page.getByRole("button", { name: "Restart ntp", exact: true });
  await expect(restart).toHaveText("");
  await restart.click();
  expect(restarts).toHaveLength(0);
  await expect(page.getByRole("dialog")).toContainText("caches, counters");
  await page.getByRole("button", { name: "Confirm restart", exact: true }).click();
  await expect(page.getByRole("region", { name: "Process health", exact: true })).toContainText("supervisor restarted");
  expect(restarts).toEqual([{ target: "ntp" }]);
  expect(backend.writes).toHaveLength(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
