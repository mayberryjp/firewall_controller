import { expect, test } from "@playwright/test";
import { mockBackend } from "./mockBackend";
import { trafficStatistics } from "../fixtures";

test("Diagnostics renders combined traffic per interface and drills into one live line", async ({ page, isMobile }, testInfo) => {
  test.setTimeout(45000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const backend = await mockBackend(page);
  let reads = 0;
  await page.route("**/proxy/statistics", route => {
    const sample = trafficStatistics(reads * 3, BigInt(reads * reads * 300));
    reads++;
    return route.fulfill({ contentType: "application/json", body: JSON.stringify(sample) });
  });
  await page.goto("/connect");
  await page.getByLabel("Registry admin password").fill("registry-test-password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("button", { name: "Connect", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Overview", exact: true })).toBeVisible();
  if (isMobile) await page.getByRole("button", { name: "Open navigation menu", exact: true }).click();
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Diagnostics", exact: true }).click();
  await expect(page).toHaveURL(/\/diagnostics\/traffic$/);
  const navigation = page.getByRole("navigation", { name: "Diagnostics pages" });
  await expect(navigation.getByRole("tab", { name: "REAL TIME TRAFFIC", exact: true })).toHaveAttribute("aria-current", "page");
  await expect(navigation.getByRole("tablist")).toHaveAttribute("aria-orientation", isMobile ? "horizontal" : "vertical");
  const bytes = page.getByRole("region", { name: "Bytes", exact: true });
  const packets = page.getByRole("region", { name: "Packets", exact: true });
  await expect(bytes.locator(".apexcharts-canvas")).toBeVisible();
  await expect(packets.locator(".apexcharts-canvas")).toBeVisible();
  await expect.poll(() => reads, { timeout: 12000 }).toBeGreaterThanOrEqual(4);
  await expect.poll(() => bytes.locator(".apexcharts-line-series .apexcharts-line").first().evaluate(path => (path as SVGPathElement).getTotalLength())).toBeGreaterThan(30);
  await expect(bytes.locator(".apexcharts-line-series .apexcharts-series")).toHaveCount(2);
  await expect(bytes.locator(".apexcharts-legend")).toContainText("eth0");
  await expect(bytes.locator(".apexcharts-legend")).toContainText("eth1");
  await expect(bytes.locator(".apexcharts-legend")).not.toContainText("Inbound");
  await expect(packets.locator(".apexcharts-line-series .apexcharts-series")).toHaveCount(2);
  await expect(packets.locator(".apexcharts-legend")).toContainText("eth0");
  await expect(packets.locator(".apexcharts-legend")).toContainText("eth1");
  await expect(bytes).toContainText("Time (UTC)");
  await expect(bytes).toContainText("bytes/s");
  await expect(packets).toContainText("packets/s");
  const interfaceBytes = bytes.locator(".apexcharts-line-series .apexcharts-line").first();
  const interfacePackets = packets.locator(".apexcharts-line-series .apexcharts-line").first();
  const bytesBefore = await interfaceBytes.getAttribute("d"), packetsBefore = await interfacePackets.getAttribute("d");
  expect(bytesBefore).toBeTruthy(); expect(packetsBefore).toBeTruthy();
  const earlierReads = reads;
  await expect.poll(() => reads, { timeout: 10000 }).toBeGreaterThanOrEqual(earlierReads + 2);
  await expect(interfaceBytes).not.toHaveAttribute("d", bytesBefore!);
  await expect(interfacePackets).not.toHaveAttribute("d", packetsBefore!);
  const interfaceSelect = page.locator(".v-select").filter({ has: page.getByRole("combobox", { name: "Watch interface", exact: true }) });
  const graphSelect = page.locator(".v-select").filter({ has: page.getByRole("combobox", { name: "Show graphs", exact: true }) });
  await interfaceSelect.click();
  await page.getByRole("option", { name: "eth1", exact: true }).click();
  await expect(interfaceSelect).toContainText("eth1");
  for (const graph of [bytes, packets]) {
    await expect(graph.locator(".apexcharts-line-series .apexcharts-series")).toHaveCount(1);
    await expect(graph.locator(".apexcharts-legend")).toContainText("eth1");
    await expect(graph.locator(".apexcharts-legend")).not.toContainText("eth0");
  }
  await graphSelect.click();
  await page.getByRole("option", { name: "Packets", exact: true }).click();
  await expect(bytes).toHaveCount(0); await expect(packets.locator(".apexcharts-canvas")).toBeVisible();
  await graphSelect.click();
  await page.getByRole("option", { name: "Both graphs", exact: true }).click();
  await expect(bytes.locator(".apexcharts-canvas")).toBeVisible();
  await expect.poll(() => bytes.locator(".apexcharts-line-series .apexcharts-line").first().evaluate(path => (path as SVGPathElement).getTotalLength())).toBeGreaterThan(30);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("real-time-traffic.png"), fullPage: true, animations: "disabled" });
  if (isMobile) await page.getByRole("button", { name: "Open navigation menu", exact: true }).click();
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Services", exact: true }).click();
  const stoppedReads = reads;
  await page.waitForTimeout(6500);
  expect(reads).toBe(stoppedReads);
  expect(backend.writes).toHaveLength(0);
  expect(errors).toEqual([]);
});
